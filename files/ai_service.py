def _load_system_prompt() -> str:
    global _SYSTEM_PROMPT
    if _SYSTEM_PROMPT is None:
        if _PROMPT_PATH.exists():
            _SYSTEM_PROMPT = _PROMPT_PATH.read_text(encoding="utf-8")
        else:
            # Fallback: minimum prompt if prompt file is not found
            _SYSTEM_PROMPT = (
                "You are an expert personal trainer. "
                "Create a personalized workout program based on the user profile. "
                "Your response MUST be strictly JSON, do not include any other text."
            )
    return _SYSTEM_PROMPT


# ─── Data Classes ─────────────────────────────────────────────────────────────

@dataclass
class HealthConditionInput:
    condition_type: str   # lumbar_hernia | knee_injury | shoulder_injury | ...
    severity: str         # mild | moderate | severe
    affected_region: Optional[str] = None
    description: Optional[str] = None


@dataclass
class PostureMetricsInput:
    """Posture metrics from cv_service.py (optional)."""
    shoulder_tilt_deg: Optional[float] = None
    hip_tilt_deg: Optional[float] = None
    spine_lateral_dev_deg: Optional[float] = None
    shoulder_width_ratio: Optional[float] = None
    head_forward_deg: Optional[float] = None
    torso_lean_deg: Optional[float] = None
    posture_score: Optional[float] = None


@dataclass
class WorkoutPlanInput:
    """
    All user context to be sent to the LLM.
    Populated from DB or request payload in main.py.
    """
    user_id: str
    full_name: str
    age: int
    gender: str
    height_cm: float
    current_weight_kg: float
    target_weight_kg: float
    fitness_level: str          # beginner | intermediate | advanced
    primary_goal: str           # weight_loss | muscle_gain | endurance | flexibility | rehabilitation

    health_conditions: list[HealthConditionInput] = field(default_factory=list)
    posture_metrics: Optional[PostureMetricsInput] = None

    available_days_per_week: int = 3
    available_equipment: list[str] = field(
        default_factory=lambda: ["dumbbell", "body weight"]
    )
    program_duration_weeks: int = 8


@dataclass
class GeneratedWorkoutPlan:
    """Parsed program from LLM + DB-ready payloads."""
    raw_json: dict                  # Raw JSON generated by LLM
    db_plan_payload: dict           # Fields to be written to workout_plans table
    db_days_payload: list[dict]     # workout_days rows
    db_exercises_payload: list[dict]# workout_day_exercises rows
    llm_provider: str               # LLM provider used
    generation_time_ms: int         # Generation time in ms
    warnings: list[str] = field(default_factory=list)


# ─── User Prompt Builder ───────────────────────────────────────────────────────

def _build_user_prompt(data: WorkoutPlanInput) -> str:
    bmi = round(data.current_weight_kg / (data.height_cm / 100) ** 2, 1)
    weight_diff = round(data.current_weight_kg - data.target_weight_kg, 1)
    weight_direction = "lose" if weight_diff > 0 else "gain"

    lines = [
        "## User Profile",
        f"- Name: {data.full_name}",
        f"- Age: {data.age} | Gender: {data.gender}",
        f"- Height: {data.height_cm} cm | Current Weight: {data.current_weight_kg} kg",
        f"- Target Weight: {data.target_weight_kg} kg (goal: {weight_direction} {abs(weight_diff):.1f} kg)",
        f"- BMI: {bmi}",
        f"- Fitness Level: {data.fitness_level}",
        f"- Primary Goal: {data.primary_goal}",
        "",
        "## Training Constraints",
        f"- Available Days Per Week: {data.available_days_per_week}",
        f"- Available Equipment: {', '.join(data.available_equipment)}",
        f"- Program Duration: {data.program_duration_weeks} weeks",
        "",
    ]

    # Health & Injury Conditions WITH MANDATORY BLACKLISTS
    if data.health_conditions:
        lines.append("## Health / Injury Conditions ⚠️ MANDATORY SAFETY RESTRICTIONS")
        for cond in data.health_conditions:
            desc = f" — {cond.description}" if cond.description else ""
            region = f" ({cond.affected_region})" if cond.affected_region else ""
            cond_name = cond.condition_type.lower()
            lines.append(f"- {cond.condition_type}{region}: severity={cond.severity}{desc}")

            # HARD-CODED INJURY BLACKLIST RULES FOR LLM
            if "knee" in cond_name:
                lines.append(
                    "  ❌ STRICTLY FORBIDDEN EXERCISES FOR KNEE INJURY: "
                    "Dumbbell Deadlift, Barbell Deadlift, Romanian Deadlift, Deep Squats, Lunges, Wall Sit, Jump Squats. "
                    "DO NOT INCLUDE ANY OF THESE IN THE PLAN. "
                    "✅ RECOMMENDED SAFE ALTERNATIVES: Glute Bridge, Seated Leg Extension (light), Upper Body movements, Standing Calf Raises."
                )
            elif "hernia" in cond_name or "lumbar" in cond_name or "back" in cond_name:
                lines.append(
                    "  ❌ STRICTLY FORBIDDEN EXERCISES FOR LUMBAR/BACK INJURY: "
                    "Barbell Deadlift, Heavy Overhead Press, Good Mornings, Weighted Crunches. "
                    "✅ RECOMMENDED SAFE ALTERNATIVES: Bird-Dog, Planks, Lat Pulldowns, Chest Press."
                )
            elif "shoulder" in cond_name:
                lines.append(
                    "  ❌ STRICTLY FORBIDDEN EXERCISES FOR SHOULDER INJURY: "
                    "Behind-the-neck Press, Upright Rows, Dip. "
                    "✅ RECOMMENDED SAFE ALTERNATIVES: Incline Dumbbell Press (controlled), Face Pulls."
                )
        lines.append("")
    else:
        lines.append("## Health Status\nNo known injuries or physical restrictions.\n")

    # Posture Metrics from CV Module
    if data.posture_metrics:
        pm = data.posture_metrics
        lines.append("## Posture Analysis Results (From CV Module)")
        if pm.posture_score is not None:
            lines.append(f"- Overall Posture Score: {pm.posture_score}/100")
        if pm.shoulder_tilt_deg is not None:
            flag = " ⚠️ HIGH" if abs(pm.shoulder_tilt_deg) > 5 else ""
            lines.append(f"- Shoulder Tilt Deviation: {pm.shoulder_tilt_deg:+.1f}°{flag}")
        if pm.hip_tilt_deg is not None:
            flag = " ⚠️ HIGH" if abs(pm.hip_tilt_deg) > 5 else ""
            lines.append(f"- Hip Tilt Deviation: {pm.hip_tilt_deg:+.1f}°{flag}")
        if pm.spine_lateral_dev_deg is not None:
            flag = " ⚠️ HIGH" if pm.spine_lateral_dev_deg > 5 else ""
            lines.append(f"- Spine Lateral Deviation: {pm.spine_lateral_dev_deg:.1f}°{flag}")
        if pm.head_forward_deg is not None:
            flag = " ⚠️ HIGH" if pm.head_forward_deg > 10 else ""
            lines.append(f"- Head Forward Lean: {pm.head_forward_deg:.1f}°{flag}")
        if pm.shoulder_width_ratio is not None:
            lines.append(f"- Shoulder/Hip Width Ratio: {pm.shoulder_width_ratio:.2f}")
        lines.append(
            "  Include corrective exercises targeting muscles affected by posture deviations, "
            "and explain why in ai_notes."
        )
        lines.append("")

    lines.append(
        "## Task\n"
        f"Generate a {data.program_duration_weeks}-week training plan with EXACTLY {data.available_days_per_week} active training days per week "
        "tailored to the profile above, FULLY compliant with the JSON schema in the system prompt.\n"
        "IMPORTANT: Output MUST be complete and valid JSON. Keep descriptions concise to prevent truncation.\n"
        "Response: strictly valid JSON only. No explanations, comments, or markdown."
    )
    lines.append(
        "## LANGUAGE CONSTRAINT (CRITICAL)\n"
        "ALL text values in the JSON output MUST be strictly in Standard ENGLISH.\n"
        "Do NOT use Turkish words like 'Pazartesi', 'Tam Vücut', 'Kilo Verme', 'Diz açısını koru'.\n"
        "Use English equivalents: 'Monday - Full Body', 'Weight Loss Plan', 'Protect knee angle, avoid deep squats'."
    )

    return "\n".join(lines)


# ─── JSON Extractor ───────────────────────────────────────────────────────────

def _extract_json(raw_text: str) -> str:
    match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", raw_text, re.DOTALL)
    if match:
        return match.group(1)

    start = raw_text.find("{")
    end   = raw_text.rfind("}")
    if start != -1 and end != -1 and end > start:
        return raw_text[start:end + 1]

    return raw_text.strip()


# ─── JSON Validator ───────────────────────────────────────────────────────────

def _validate_plan_json(plan: dict) -> list[str]:
    warnings: list[str] = []
    required_top = ["plan_name", "duration_weeks", "sessions_per_week", "weeks"]
    for key in required_top:
        if key not in plan:
            warnings.append(f"Missing field: '{key}'")

    if "weeks" not in plan:
        return warnings

    if not isinstance(plan["weeks"], list) or len(plan["weeks"]) == 0:
        warnings.append("'weeks' is empty or not a list.")
        return warnings

    for wi, week in enumerate(plan["weeks"]):
        if "days" not in week:
            warnings.append(f"week[{wi}] is missing 'days'.")
            continue
        for di, day in enumerate(week["days"]):
            if day.get("day_type") == "workout" and not day.get("exercises"):
                warnings.append(
                    f"week[{wi}].day[{di}] is of type 'workout' but has an empty exercise list."
                )
            for ei, ex in enumerate(day.get("exercises", [])):
                if not ex.get("name"):
                    warnings.append(f"week[{wi}].day[{di}].exercises[{ei}] missing 'name'.")
                if not ex.get("sets"):
                    warnings.append(f"Missing 'sets' for '{ex.get('name','?')}'.")
                expected_order = ei + 1
                if ex.get("order_index") != expected_order:
                    ex["order_index"] = expected_order

    return warnings


# ─── DB Payload Builder ───────────────────────────────────────────────────────

def _build_db_payloads(
    plan: dict, user_id: str
) -> tuple[dict, list[dict], list[dict]]:
    plan_payload = {
        "user_id":          user_id,
        "plan_name":        plan.get("plan_name", "AI Workout Plan"),
        "duration_weeks":   plan.get("duration_weeks", 8),
        "sessions_per_week":plan.get("sessions_per_week", 3),
        "difficulty":       plan.get("difficulty", "beginner"),
        "estimated_months": plan.get("estimated_months"),
        "ai_reasoning":     plan.get("ai_reasoning"),
        "is_active":        True,
        "generated_by":     "ai",
    }

    days_payload:      list[dict] = []
    exercises_payload: list[dict] = []

    for week in plan.get("weeks", []):
        week_num = week.get("week_number", 1)
        for day in week.get("days", []):
            day_row = {
                "week_number":  week_num,
                "day_number":   day.get("day_number", 1),
                "day_label":    day.get("day_label"),
                "muscle_focus": day.get("muscle_focus"),
                "day_type":     day.get("day_type", "workout"),
                "_exercises":   [],
            }
            for ex in day.get("exercises", []):
                day_row["_exercises"].append({
                    "exercise_name": ex.get("name"),
                    "body_part":     ex.get("body_part"),
                    "equipment":     ex.get("equipment"),
                    "sets":          ex.get("sets", 3),
                    "reps":          str(ex.get("reps", "12")),
                    "rest_seconds":  ex.get("rest_seconds", 60),
                    "order_index":   ex.get("order_index", 1),
                    "ai_notes":      ex.get("ai_notes"),
                })
            days_payload.append(day_row)

    return plan_payload, days_payload, exercises_payload


# ─── LLM Calls ───────────────────────────────────────────────────────────────

async def _call_openai(system_prompt: str, user_prompt: str) -> str:
    api_key = os.getenv("OPENAI_API_KEY") or getattr(settings, "openai_api_key", None)
    if not _OPENAI_AVAILABLE:
        raise RuntimeError("openai package is not installed: pip install openai")
    if not api_key:
        raise RuntimeError("OPENAI_API_KEY is not defined in .env file.")

    client = AsyncOpenAI(api_key=api_key)
    response = await client.chat.completions.create(
        model="gpt-4o-mini",
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user",   "content": user_prompt},
        ],
        temperature=0.3,
        max_tokens=8192,  
        response_format={"type": "json_object"},
    )
    return response.choices[0].message.content


async def _call_anthropic(system_prompt: str, user_prompt: str) -> str:
    if not _ANTHROPIC_AVAILABLE:
        raise RuntimeError("anthropic package is not installed: pip install anthropic")
    if not settings.anthropic_api_key:
        raise RuntimeError("ANTHROPIC_API_KEY is not defined in .env file.")

    client = AsyncAnthropic(api_key=settings.anthropic_api_key)
    message = await client.messages.create(
        model="claude-sonnet-4-6",
        max_tokens=8192,
        system=system_prompt,
        messages=[{"role": "user", "content": user_prompt}],
        temperature=0.3,
    )
    return message.content[0].text


# ─── Main Service Function ───────────────────────────────────────────────────

async def generate_workout_plan(
    data: WorkoutPlanInput,
    preferred_provider: str = "auto",
) -> GeneratedWorkoutPlan:
    t_start = time.perf_counter()

    system_prompt = _load_system_prompt()
    user_prompt   = _build_user_prompt(data)

    openai_key = os.getenv("OPENAI_API_KEY") or getattr(settings, "openai_api_key", None)
    anthropic_key = os.getenv("ANTHROPIC_API_KEY") or getattr(settings, "anthropic_api_key", None)

    provider = preferred_provider
    if provider == "auto":
        if _OPENAI_AVAILABLE and openai_key:
            provider = "openai"
        elif _ANTHROPIC_AVAILABLE and anthropic_key:
            provider = "anthropic"
        else:
            raise RuntimeError(
                f"No LLM API key found. (OpenAI Installed: {_OPENAI_AVAILABLE}, Key Loaded: {bool(openai_key)})"
            )

    if provider == "openai":
        raw_text = await _call_openai(system_prompt, user_prompt)
    elif provider == "anthropic":
        raw_text = await _call_anthropic(system_prompt, user_prompt)
    else:
        raise ValueError(f"Unknown provider: {provider}. Use 'openai' or 'anthropic'.")

    clean_json = _extract_json(raw_text)
    try:
        plan_dict = json.loads(clean_json)
    except json.JSONDecodeError as exc:
        raise ValueError(
            f"LLM did not return valid JSON: {exc}\n"
            f"Raw response (first 500 chars): {raw_text[:500]}"
        ) from exc

    validation_warnings = _validate_plan_json(plan_dict)

    plan_payload, days_payload, exercises_payload = _build_db_payloads(
        plan_dict, data.user_id
    )

    elapsed_ms = int((time.perf_counter() - t_start) * 1000)

    return GeneratedWorkoutPlan(
        raw_json=plan_dict,
        db_plan_payload=plan_payload,
        db_days_payload=days_payload,
        db_exercises_payload=exercises_payload,
        llm_provider=provider,
        generation_time_ms=elapsed_ms,
        warnings=validation_warnings,
    )


def preview_prompt(data: WorkoutPlanInput) -> dict[str, str]:
    return {
        "system_prompt": _load_system_prompt(),
        "user_prompt":   _build_user_prompt(data),
    }


async def generate_posture_comparison_report(
    baseline_metrics: dict, 
    new_metrics: dict, 
    score_change: float
) -> dict:
    prompt = f"""
You are an expert posture coach for AuraFit AI.
Analyze these posture metric changes between Baseline and Current Month:
- Score Change: {score_change:+.1f} points
- Metrics Data: {new_metrics}

Generate a concise assessment JSON matching strictly this format:
{{
  "overall_verdict": "One sentence summary of overall progress.",
  "score_change_comment": "Detailed comment on why the score changed.",
  "highlights": ["1-2 positive improvements observed"],
  "areas_to_focus": ["1-2 posture areas that still need work"],
  "motivational_note": "A short encouraging closing note.",
  "next_month_tips": ["Tip 1 for next month", "Tip 2 for next month"]
}}
Return ONLY valid JSON in English.
"""

    openai_key = os.getenv("OPENAI_API_KEY") or getattr(settings, "openai_api_key", None)
    if _OPENAI_AVAILABLE and openai_key:
        try:
            client = AsyncOpenAI(api_key=openai_key)
            resp = await client.chat.completions.create(
                model="gpt-4o-mini",
                messages=[{"role": "user", "content": prompt}],
                temperature=0.3,
                response_format={"type": "json_object"},
            )
            return json.loads(resp.choices[0].message.content)
        except Exception as e:
            print(f"OpenAI Posture Report Error: {e}")

    api_key = getattr(settings, "gemini_api_key", None) or os.getenv("GEMINI_API_KEY")
    if api_key:
        try:
            import google.generativeai as genai
            genai.configure(api_key=api_key)
            model = genai.GenerativeModel('gemini-2.0-flash')
            response = await model.generate_content_async(prompt)
            clean_text = _extract_json(response.text)
            return json.loads(clean_text)
        except Exception as e:
            print(f"Gemini API Fallback Triggered: {e}")

    return {
        "overall_verdict": "Progress analysis completed based on computer vision metrics.",
        "score_change_comment": f"Your posture score changed by {score_change:+.1f} points.",
        "highlights": ["Computer vision posture calculations completed successfully."],
        "areas_to_focus": ["Maintain daily posture awareness exercises."],
        "motivational_note": "Consistency is key to long-term ergonomic improvements!",
        "next_month_tips": ["Perform daily chest stretches", "Adjust monitor eye-level alignment"]
    }